// Tall Order: stacking is the core. Stand on your mate's head for a boost, or, with your mate on your head,
// press Toss to throw them about 6 tiles up. The one left below follows by plates, springs, crates, lifts and
// fold-out steps (P and Q, solid only while plate u or i is held, and never inside someone).
import { overlap } from './engine.js';
import { plateColour, roundRect } from './draw.js';

const TOSS = 23.5; // about 6.5 tiles of rise
const step = (k) => ({
  kind: 'step', key: k,
  solid: (w, b, c, r) => !!w.open[k] && !(b && overlap(b, { x: c, y: r, w: 1, h: 1 }, 0.02)),
  draw(g, c, r, w) {
    if (w.open[k]) { g.fillStyle = plateColour(k); roundRect(g, c + 0.02, r, 0.96, 0.5, 0.08); g.fill(); g.fillStyle = 'rgba(0,0,0,.2)'; g.fillRect(c + 0.02, r + 0.38, 0.96, 0.12); }
    else { g.strokeStyle = plateColour(k); g.globalAlpha = 0.45; g.lineWidth = 0.04; g.setLineDash([0.1, 0.1]); g.strokeRect(c + 0.08, r + 0.05, 0.84, 0.4); g.setLineDash([]); g.globalAlpha = 1; }
  },
});

// is q standing (or just about to stand) on p's head?
const onHead = (p, q) => !q.dead && q.gdir === 1 && (q.on === p || (Math.abs(q.y + q.h - p.y) < 0.25 && q.x < p.x + p.w - 0.05 && p.x < q.x + q.w - 0.05));

