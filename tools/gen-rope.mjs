// Builds the Sweet Drop levels from tools/rope/designs.mjs: finds a winning plan for each design with the
// solver, places three stars along the sweet's path and writes www/js/rope-levels.js.
// Run with: node tools/gen-rope.mjs
import { writeFileSync } from 'node:fs';
import { DESIGNS } from './rope/designs.mjs';
import { solve, replay } from '../www/js/rope-engine.js';

const r2 = (v) => Math.round(v * 100) / 100;
const out = [];
let bad = 0;
DESIGNS.forEach((d, i) => {
  const L = { candy: d.c, ropes: d.r, frog: d.f, stars: [], bubbles: d.b || [], spikes: d.s || [], hooks: d.k || [] };
  let stars = d.stars;
  if (!stars) {
    const sol = solve(L, { needStars: 0 });
    if (!sol) { console.log(`level ${i + 1}: NO WIN`); bad++; return; }
    // stars at fractions of the path length, skipping the very start and the frog's mouth
    const p = sol.path, acc = [0];
    for (let k = 1; k < p.length; k++) acc.push(acc[k - 1] + Math.hypot(p[k][0] - p[k - 1][0], p[k][1] - p[k - 1][1]));
    const total = acc[acc.length - 1];
    // only spots well inside the board count, so a star is never drawn half off the edge
    // and never on top of a bubble, a hook pin or the frog
    const clear = (x, y) => [...L.bubbles, ...L.hooks, L.frog].every(([bx, by]) => Math.hypot(bx - x, by - y) > 1.3);
    const okAt = (k) => p[k][0] > 0.5 && p[k][0] < 9.5 && p[k][1] > 0.5 && p[k][1] < 14.5 && clear(p[k][0], p[k][1]);
    stars = (d.at || [0.28, 0.55, 0.8]).map((f) => {
      let k = acc.findIndex((a) => a >= f * total);
      for (let j = 0; j < p.length && !okAt(k); j++) { const a = k - j, b = k + j; if (a >= 0 && okAt(a)) { k = a; break; } if (b < p.length && okAt(b)) { k = b; break; } }
      return [r2(p[k][0]), r2(p[k][1])];
    });
    L.stars = stars;
    const chk = replay(L, sol.plan);
    console.log(`level ${i + 1}: ${chk.state} with ${chk.stars} stars, plan ${JSON.stringify(sol.plan)}`);
    if (chk.state !== 'won' || chk.stars < 3) bad++;
  }
  L.stars = stars;
  const lv = { candy: L.candy, ropes: L.ropes, frog: L.frog, stars };
  if (L.bubbles.length) lv.bubbles = L.bubbles;
  if (L.spikes.length) lv.spikes = L.spikes;
  if (L.hooks.length) lv.hooks = L.hooks;
  out.push(lv);
});
const body = out.map((l) => '  ' + JSON.stringify(l)).join(',\n');
writeFileSync(new URL('../www/js/rope-levels.js', import.meta.url),
  `// Sweet Drop levels, generated by tools/gen-rope.mjs from tools/rope/designs.mjs. Do not edit by hand.\n// Board is 10 x 15 units, y down. See www/js/rope-engine.js for the format.\nexport const LEVELS = [\n${body},\n];\n`);
console.log(`${out.length} levels written, ${bad} with problems`);
if (bad) process.exit(1);
